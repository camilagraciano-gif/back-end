export function banhoGato(raca, servico){
    return `${raca} fez serviço: ${servico}`
}

export function tosaGato(pelagem, servico){
    return `${pelagem} é tosa: ${servico}`
}

export function alimentarGato(tamanho, quantidade){
    return `${tamanho} tem ração de: ${quantidade}`
}

